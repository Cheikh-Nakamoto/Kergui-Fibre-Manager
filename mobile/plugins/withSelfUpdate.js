// The website APK updates itself through the hub (#65, #74); the Play bundle
// never does (Play policy). One prebuild serves both, so the difference is a
// Gradle property: mobile-release passes -Pkergui.selfUpdate=true to the
// website's assembleRelease only. With it, the release build's manifest gets
// an overlay (android/app/src/selfUpdate/AndroidManifest.xml) that adds:
//   - the REQUEST_INSTALL_PACKAGES permission,
//   - the org.kergui.selfUpdate flag the native module reads (selfUpdateInfo),
//   - the FileProvider the system installer reads the downloaded APK through.
// Without the property (bundleRelease, debug builds) none of it is there.
const fs = require('fs');
const path = require('path');
const { withAppBuildGradle, withDangerousMod } = require('expo/config-plugins');

const MARKER = '// kergui-self-update';
const OVERLAY = 'src/selfUpdate/AndroidManifest.xml';

const MANIFEST = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withSelfUpdate.js: the website APK only (-Pkergui.selfUpdate=true). -->
<manifest xmlns:android="http://schemas.android.com/apk/res/android">
  <uses-permission android:name="android.permission.REQUEST_INSTALL_PACKAGES" />
  <application>
    <meta-data android:name="org.kergui.selfUpdate" android:value="true" />
    <provider
      android:name="org.kergui.core.UpdateFileProvider"
      android:authorities="\${applicationId}.kergui.update"
      android:exported="false"
      android:grantUriPermissions="true">
      <meta-data android:name="android.support.FILE_PROVIDER_PATHS" android:resource="@xml/kergui_update_paths" />
    </provider>
  </application>
</manifest>
`;

const GRADLE = `
${MARKER}: the website APK's manifest overlay (plugins/withSelfUpdate.js).
if (findProperty('kergui.selfUpdate')?.toString() == 'true') {
    android {
        sourceSets {
            release {
                manifest.srcFile '${OVERLAY}'
            }
        }
    }
}
`;

function addSelfUpdate(gradle) {
  if (gradle.includes(MARKER)) return gradle;
  if (!/\bandroid\s*\{/.test(gradle)) throw new Error('withSelfUpdate: no android block in app/build.gradle');
  if (/sourceSets\s*\{[\s\S]*?release\s*\{[\s\S]*?manifest/.test(gradle)) {
    throw new Error('withSelfUpdate: app/build.gradle already sets a release manifest');
  }
  return gradle.replace(/\s*$/, '\n') + GRADLE;
}

const withSelfUpdate = (config) => {
  config = withAppBuildGradle(config, (cfg) => {
    if (cfg.modResults.language !== 'groovy') throw new Error('withSelfUpdate: expected a Groovy build.gradle');
    cfg.modResults.contents = addSelfUpdate(cfg.modResults.contents);
    return cfg;
  });
  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      const appDir = path.join(cfg.modRequest.platformProjectRoot, 'app');
      const release = path.join(appDir, 'src/release/AndroidManifest.xml');
      if (fs.existsSync(release)) throw new Error('withSelfUpdate: src/release/AndroidManifest.xml exists and would be replaced');
      const file = path.join(appDir, OVERLAY);
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, MANIFEST);
      return cfg;
    },
  ]);
};

module.exports = withSelfUpdate;
module.exports.addSelfUpdate = addSelfUpdate;
module.exports.MANIFEST = MANIFEST;
